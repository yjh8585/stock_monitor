NOW = datetime.now(timezone.utc).isoformat()


def _get_financials(client, company_id: str) -> dict:
    """최근 연간 실적 데이터를 가져온다 (2022~2025)."""
    rows = (
        client.table('financials')
        .select('fiscal_year,revenue,operating_income,operating_margin')
        .eq('company_id', company_id)
        .eq('period_type', 'annual')
        .in_('fiscal_year', [2022, 2023, 2024, 2025])
        .order('fiscal_year')
        .execute()
        .data
    )
    return {str(r['fiscal_year']): r for r in rows}


def _update(client, ticker: str, summary: str) -> None:
    client.table('companies').update({
        'business_summary': summary,
        'summary_updated_at': NOW,
    }).eq('ticker', ticker).execute()


